import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'
import {openQaPage,waitFor,delay} from './browser-cdp.mjs'

const page=await openQaPage()
try{
 await page.call('Emulation.setDeviceMetricsOverride',{width:1365,height:1000,deviceScaleFactor:1,mobile:false})
 await page.call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
 await page.call('Page.navigate',{url:`${process.env.QA_WEB_URL??'http://127.0.0.1:5173'}/scripts/fixtures/onboarding-preview.html`})
 await waitFor(page,`[...document.querySelectorAll('button')].some(b=>b.textContent.includes('安排第一批居民'))`)
 await page.evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes('安排第一批居民')).click()`)
 await waitFor(page,`document.querySelector('.personal-values')`)
 assert.equal(await page.evaluate(`document.querySelector('.personal-values').open`),false,'Optional identity controls must not expand the initial form')
 await page.evaluate(`document.querySelector('.personal-values summary').click()`)
 await page.evaluate(`document.querySelectorAll('.personal-values input')[1].click()`)
 await delay(100)
 await page.evaluate(`document.querySelectorAll('.personal-values input')[3].click()`)
 await delay(100)
 await page.evaluate(`document.querySelectorAll('.personal-values input')[2].click()`)
 await delay(100)
 assert.equal(await page.evaluate(`document.querySelectorAll('.personal-values input:checked').length`),3)
 assert.equal(await page.evaluate(`document.querySelectorAll('.personal-values input:disabled').length`),3)
 await page.evaluate(`document.querySelector('.personal-values textarea').focus()`)
 await page.call('Input.insertText',{text:'想照顾别人，也不想被当成理所当然。'})
 await page.evaluate(`document.querySelectorAll('.onboarding-roster > div > button')[1].click()`)
 await delay(150)
 assert.equal(await page.evaluate(`document.querySelectorAll('.personal-values input:checked').length`),0,'Editing one resident must not alter another')
 await page.evaluate(`document.querySelectorAll('.onboarding-roster > div > button')[0].click()`)
 await delay(150)
 assert.equal(await page.evaluate(`document.querySelectorAll('.personal-values input:checked').length`),3)
 await page.call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
 await page.evaluate(`document.querySelector('.personal-values').open=true;document.querySelector('.personal-values').scrollIntoView({block:'center'})`)
 await delay(350)
 assert.equal(await page.evaluate(`document.documentElement.scrollWidth`),390,'Mobile editor must not overflow horizontally')
 const boxes=await page.evaluate(`[...document.querySelectorAll('.personal-values__choices label')].map(n=>{const r=n.getBoundingClientRect();return {x:r.x,right:r.right,height:r.height}})`)
 assert.ok(boxes.every(b=>b.x>=0&&b.right<=390&&b.height>=44),'Choices must fit and have touch-sized targets')
 if(process.env.QA_SCREENSHOT){const shot=await page.call('Page.captureScreenshot',{format:'png'});await writeFile(process.env.QA_SCREENSHOT,Buffer.from(shot.data,'base64'))}
 await page.evaluate(`document.querySelector('.onboarding-editor').requestSubmit()`)
 await waitFor(page,`window.qaOnboardingPayload`)
 const residents=await page.evaluate(`window.qaOnboardingPayload.residents`)
 const first=residents[0].profile??residents[0]
 assert.deepEqual(first.values,['fairness','autonomy','care'])
 assert.equal(first.selfImage,'想照顾别人，也不想被当成理所当然。')
 await page.call('Page.navigate',{url:`${process.env.QA_WEB_URL??'http://127.0.0.1:5173'}/scripts/fixtures/onboarding-preview.html?language=en`})
 await waitFor(page,`document.querySelector('.onboarding-loop .onboarding-primary')`)
 await page.evaluate(`document.querySelector('.onboarding-loop .onboarding-primary').click()`)
 await waitFor(page,`document.querySelector('.personal-values')`)
 assert.equal(await page.evaluate(`document.querySelector('.personal-values summary').textContent`),'Inner character (optional)')
 await page.evaluate(`document.querySelector('.personal-values summary').click()`)
 const english=await page.evaluate(`document.querySelector('.personal-values').textContent`)
 assert.ok(english.includes('Fairness')&&english.includes('The person they hope to be'))
 assert.ok(!/[\u4e00-\u9fff]/u.test(english),'All new control labels must follow the interface language')
 assert.deepEqual(page.errors,[])
 assert.deepEqual(page.consoleErrors,[])
 console.log('Personal values browser passed: collapsed optional setup, priority and limit, per-resident isolation, self-image input, 390px touch layout, English labels and real onboarding payload. No account writes.')
}finally{await page.close()}
